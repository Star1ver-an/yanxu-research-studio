import { readFileSync } from 'node:fs';
import js from '@eslint/js';
import { parse } from 'espree';
import globals from 'globals';

function bindingNames(node) {
  if (!node) return [];
  if (node.type === 'Identifier') return [node.name];
  if (node.type === 'ArrayPattern') return node.elements.flatMap(bindingNames);
  if (node.type === 'ObjectPattern') {
    return node.properties.flatMap((property) =>
      bindingNames(property.type === 'RestElement' ? property.argument : property.value),
    );
  }
  return bindingNames(node.type === 'RestElement' ? node.argument : node.left);
}

// Keep the existing classic scripts. Only declarations in scripts loaded by the
// entry page count as shared globals; undeclared names still fail no-undef.
const entry = readFileSync(new URL('./web/index.html', import.meta.url), 'utf8');
const declarations = new Map();
for (const [, filename] of entry.matchAll(/<script\b[^>]*\bsrc=["']\/([^"']+\.js)["']/g)) {
  if (filename === 'locales.js') continue; // Generated by the local server, attached to window.
  const source = readFileSync(new URL(`./web/${filename}`, import.meta.url), 'utf8');
  const names = {};
  for (const statement of parse(source, { ecmaVersion: 'latest', sourceType: 'script' }).body) {
    if (statement.type === 'VariableDeclaration') {
      for (const declaration of statement.declarations) {
        for (const name of bindingNames(declaration.id)) {
          names[name] = statement.kind === 'const' ? 'readonly' : 'writable';
        }
      }
    } else if (['FunctionDeclaration', 'ClassDeclaration'].includes(statement.type)) {
      names[statement.id.name] = 'readonly';
    }
  }
  declarations.set(filename, names);
}
const shared = Object.assign({}, ...declarations.values());

export default [
  {
    files: ['web/*.js'],
    languageOptions: { sourceType: 'script', globals: globals.browser },
    rules: {
      ...js.configs.recommended.rules,
      'no-empty': ['error', { allowEmptyCatch: true }],
      // Entry points are called across files; still check unused function locals.
      'no-unused-vars': [
        'error',
        { vars: 'local', args: 'none', caughtErrors: 'none', ignoreRestSiblings: true },
      ],
    },
  },
  ...Array.from(declarations, ([filename, own]) => ({
    files: [`web/${filename}`],
    languageOptions: {
      globals: Object.fromEntries(
        Object.entries(shared).filter(([name]) => !Object.hasOwn(own, name)),
      ),
    },
  })),
  {
    files: ['eslint.config.mjs'],
    languageOptions: { globals: globals.node },
    rules: js.configs.recommended.rules,
  },
];
