def blueprints():
    return copy.deepcopy(BLUEPRINTS)


def blueprint(key):
    item = next((x for x in BLUEPRINTS if x['id'] == key), None)
    if item is None:
        raise ValueError('未找到此研究方案。')
    return copy.deepcopy(item)


def brief_context(p):
    brief = p.get('study_brief', {})
    if not brief:
        return ''
    guide = PROFILES.get(brief.get('profile'), PROFILES['general'])
    content = '\n研究领域的解释边界：' + guide
    if brief.get('context_enabled'):
        content += '\n研究简报（' + ('已由作者核对研究范围' if brief.get('status') == 'confirmed' else '待作者核对的方案草稿')
        content += '；不是实验结果或获利/政策效果证据）：\n' + json.dumps(brief['fields'], ensure_ascii=False)
    return content


def reset_brief(p):
    """Copies and restored workspaces must not inherit approval or enablement."""
    if 'study_brief' in p:
        p['study_brief'].update(status='draft', context_enabled=False)
        p['study_brief'].pop('confirmed_at', None)
        p.pop('study_brief_history', None)


def restored_brief(value):
    if not isinstance(value, dict) or value.get('profile') not in PROFILES:
        raise ValueError('备份研究简报领域无效。')
    fields = value.get('fields')
    if not isinstance(fields, dict) or set(fields) != set(FIELDS):
        raise ValueError('备份研究简报字段无效。')
    for key, (_, limit) in FIELDS.items():
        if not isinstance(fields[key], str) or len(fields[key]) > limit:
            raise ValueError('备份研究简报内容无效。')
    if not fields['working_title'].strip() or not fields['question'].strip():
        raise ValueError('备份研究简报缺少名称或问题。')
    key = value.get('blueprint', '')
    if not isinstance(key, str):
        raise ValueError('备份研究方案标识无效。')
    if key:
        blueprint(key)
    return dict(schema=1, revision=1, profile=value['profile'], blueprint=key,
                fields=copy.deepcopy(fields), status='draft', context_enabled=False, updated=now())


class Studies:
    def study_create(self, data):
        plan = blueprint(data.get('blueprint'))
        with self.lock:
            if self.updating:
                raise ValueError('软件正在更新，请稍后创建项目。')
            # Idempotent retries reuse the same project; copies have a new identity.
            existing = next((p for p in self.store.list()
                             if p.get('study_origin') == plan['id'] and p.get('lifecycle', 'active') != 'trash'), None)
            if existing:
                return self.public_project(existing['id'])
            from .workflows import FLOWS
            p = self.store.create(dict(title=plan['title'], topic=plan['fields']['question'],
                                      discipline=plan['discipline'], flow=plan['flow'],
                                      route=FLOWS[plan['flow']]['route'], experiments='none' if plan['profile']=='biomedical' else 'undecided',
                                      data_kind='unknown', citation='Vancouver' if plan['profile'] == 'biomedical' else 'GB/T 7714'), persist=False)
            # Assemble then commit as one database transaction, including the create.
            p['study_origin'] = plan['id']
            p['study_brief'] = dict(schema=1, revision=1, profile=plan['profile'], blueprint=plan['id'],
                                    status='draft', context_enabled=False, fields=plan['fields'], updated=now())
            for task in plan['tasks']:
                self.prepare_research_record(p, 'tasks', dict(title=task['title'], purpose='研究准备任务；不代表已执行',
                                                            materials=task['materials'], criterion=task['criterion'],
                                                            status='todo', depends_on='', due='', stage=''))
            self.store.put(p)
            return self.public_project(p['id'])

    def study_save(self, pid, data):
        fields = data.get('fields')
        if not isinstance(fields, dict) or set(fields) != set(FIELDS):
            raise ValueError('研究简报字段不完整，请重新打开编辑。')
        clean = {}
        for key, (label, limit) in FIELDS.items():
            if not isinstance(fields[key], str) or len(fields[key]) > limit:
                raise ValueError(label + '内容过长或格式无效。')
            clean[key] = fields[key].strip()
        if not clean['working_title'] or not clean['question']:
            raise ValueError('请填写课题名称与核心研究问题。')
        if type(data.get('context_enabled')) is not bool:
            raise ValueError('请选择是否将简报用于模型研究。')
        confirm = data.get('confirm', False)
        if type(confirm) is not bool or confirm and data.get('acknowledge') is not True:
            raise ValueError('请确认已核对研究范围；这不代表科学结论已验证。')
        with self.lock:
            p = self.store.get(pid)
            self.assert_idle(p)
            if self.assistant.busy(pid):
                raise ValueError('请等待助手完成后再修改研究简报。')
            old = p.get('study_brief', {})
            revision = old.get('revision', 0)
            if type(data.get('revision')) is not int or data['revision'] != revision:
                raise ValueError('研究简报已在其他页面更新，请保留草稿后重新打开核对。')
            changed = old.get('fields') != clean or old.get('context_enabled', False) != data['context_enabled']
            if changed and (old.get('context_enabled') or data['context_enabled']):
                self.invalidate_inputs(p)
            brief = dict(schema=1, revision=revision + 1, profile=old.get('profile', 'general'),
                         blueprint=old.get('blueprint', ''), fields=clean, context_enabled=data['context_enabled'],
                         status='confirmed' if confirm else 'draft', updated=now())
            if confirm:
                brief['confirmed_at'] = now()
            if old:
                history = p.setdefault('study_brief_history', [])
                history.append(copy.deepcopy(old))
                p['study_brief_history'] = history[-10:]
            p['study_brief'] = brief
            self.store.put(p)
            return self.public_project(pid)

    def study_export(self, pid, data=None):
        p = self.store.get(pid)
        brief = p.get('study_brief')
        if not brief:
            raise ValueError('此项目尚未保存研究简报。')
        sections = ['# ' + brief['fields']['working_title'],
                    '状态：' + ('已核对研究范围' if brief['status'] == 'confirmed' else '研究方案草稿 · 待核对'),
                    '本文件是研究计划，不包含新生成的实验结果、投资收益或政策效果。']
        sections += ['## ' + label + '\n\n' + brief['fields'].get(key, '') for key, (label, _) in FIELDS.items()]
        sections += ['## 领域要求\n\n' + PROFILES[brief['profile']]]
        if brief.get('blueprint'):
            sections += ['## 起步参考来源\n\n' + '\n'.join('- [' + s['title'] + '](' + s['url'] + ')：' + s['use']
                                                          for s in blueprint(brief['blueprint'])['sources'])]
        return '研究简报.md', '\n\n'.join(sections).encode('utf-8'), 'text/markdown; charset=utf-8'
